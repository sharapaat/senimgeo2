function initEarthquakeMap() {
  const mapContainer = document.getElementById('seismicMap');

  if (!mapContainer || seismicMap) {
    return;
  }

  seismicMap = L.map('seismicMap', {
    zoomControl: true,
    attributionControl: true,
  }).setView([45, 60], 3);

  L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
    attribution: '&copy; OpenStreetMap contributors',
  }).addTo(seismicMap);

  setTimeout(() => {
    if (seismicMap) {
      seismicMap.invalidateSize();
    }
  }, 200);
}

function populateSeismicCities() {
  const countrySelect = document.getElementById('seismicCountry');
  const citySelect = document.getElementById('seismicCity');

  if (!countrySelect || !citySelect) {
    return;
  }

  const country = countrySelect.value;
  const cities = seismicCities[country] || [];

  citySelect.innerHTML = '';

  if (!cities.length) {
    const option = document.createElement('option');
    option.value = '';
    option.textContent = 'Аудан таңдалмады';
    citySelect.appendChild(option);
    return;
  }

  cities.forEach((city) => {
    const option = document.createElement('option');
    option.value = city.value;
    option.textContent = city.label;
    citySelect.appendChild(option);
  });
}

function simulateEarthquake() {
  const countrySelect = document.getElementById('seismicCountry');
  const citySelect = document.getElementById('seismicCity');
  const resultBox = document.getElementById('earthquakeResult');

  if (!countrySelect || !citySelect || !resultBox) {
    return;
  }

  initEarthquakeMap();

  const country = countrySelect.value;
  const selectedCity = citySelect.value;
  const cityData = (seismicCities[country] || []).find(
    (city) => city.value === selectedCity,
  );

  if (!cityData) {
    resultBox.innerHTML = `
            <div class="earthquake-active">
                <div class="earthquake-icon">⚠️</div>
                <div>
                    <strong>Аудан таңдалмаған</strong>
                    <p>Мемлекет пен облыс/қаланы таңдаңыз.</p>
                </div>
            </div>
        `;
    return;
  }

  if (seismicMap) {
    seismicMap.setView(cityData.coords, cityData.zoom);

    seismicMap.eachLayer((layer) => {
      if (
        layer instanceof L.Circle ||
        layer instanceof L.Marker ||
        layer instanceof L.CircleMarker
      ) {
        seismicMap.removeLayer(layer);
      }
    });

    const epicenter = L.marker(cityData.coords).addTo(seismicMap);
    epicenter
      .bindPopup(`<strong>${cityData.label}</strong><br>Эпицентр`)
      .openPopup();

    L.circle(cityData.coords, {
      radius: 120000,
      color: '#dc2626',
      fillColor: '#dc2626',
      fillOpacity: 0.5,
      weight: 2,
    }).addTo(seismicMap);

    L.circle(cityData.coords, {
      radius: 260000,
      color: '#f97316',
      fillColor: '#f97316',
      fillOpacity: 0.22,
      weight: 2,
    }).addTo(seismicMap);

    L.circle(cityData.coords, {
      radius: 420000,
      color: '#facc15',
      fillColor: '#facc15',
      fillOpacity: 0.18,
      weight: 2,
    }).addTo(seismicMap);
  }

  const riskText =
    cityData.magnitude >= 7
      ? 'Жоғары қауіп'
      : cityData.magnitude >= 6
        ? 'Орташа қауіп'
        : 'Ескерту аймағы';

  resultBox.innerHTML = `
        <div class="earthquake-active">
            <div class="earthquake-icon">📍</div>
            <div>
                <strong>${cityData.label} — эпицентр</strong>
                <p>Сейсмикалық белсенділік: ${riskText}. Магнитуда: ${cityData.magnitude.toFixed(1)}.</p>
            </div>
            <span class="earthquake-warning">${riskText}</span>
        </div>
    `;
}

