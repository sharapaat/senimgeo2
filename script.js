function finishUBT() {
  const total = ubtQuestions[ubtCurrentSubject].length;

  const subjectNames = {
    kzHistory: 'Қазақстан тарихы',
    reading: 'Оқу сауаттылығы',
    math: 'Математикалық сауаттылық',
    geography: 'География',
    worldHistory: 'Дүниежүзі тарихы',
  };

  const subjectName = subjectNames[ubtCurrentSubject];

  const result = {
    name: ubtStudent,
    subject: subjectName,
    score: ubtScore,
    total: total,
    percent: Math.round((ubtScore / total) * 100),
    date: new Date().toLocaleString('kk-KZ'),
  };

  // ---- localStorage-та бар нәтижені тексеру ----
  let saved = JSON.parse(localStorage.getItem('ubtResults') || '[]');

  // Сол оқушы + сол пән бойынша бұрынғы жазбаны өшіреміз
  saved = saved.filter(
    (r) => !(r.name === result.name && r.subject === result.subject)
  );

  // Жаңа нәтижені қосамыз
  saved.push(result);

  localStorage.setItem('ubtResults', JSON.stringify(saved));

  // Экранда көрсету
  document.getElementById('ubtQuestionText').innerHTML =
    `Тест аяқталды!<br><br><strong>${ubtScore}/${total}</strong><br>${result.percent}%`;

  document.getElementById('ubtAnswers').innerHTML = `
    <div class="final-result">
      <h3>${result.percent >= 70 ? 'Жақсы нәтиже!' : 'Қайталау керек.'}</h3>
      <p>${ubtStudent} — ${result.subject}</p>
      <p>Балл: <strong>${ubtScore}/${total}</strong> (${result.percent}%)</p>
    </div>
  `;

  document.getElementById('ubtAnswerResult').innerHTML = '';
  document.getElementById('ubtNextButton').style.display = 'none';

  loadUBTResults();
}

/* =====================================================
   ҰБТ — НӘТИЖЕЛЕРДІ ШЫҒАРУ
===================================================== */

function loadUBTResults() {
  const list = document.getElementById('ubtResultsList');
  if (!list) return;

  const saved = JSON.parse(localStorage.getItem('ubtResults') || '[]');

  if (saved.length === 0) {
    list.innerHTML = '<p style="color:#64748b;">Әзірге нәтиже жоқ.</p>';
    return;
  }

  // Оқушыларды топтастыру
  const students = {};

  saved.forEach((r) => {
    if (!students[r.name]) {
      students[r.name] = {
        name: r.name,
        subjects: [],
        scoreSum: 0,
        totalSum: 0,
        date: r.date,
      };
    }
    students[r.name].subjects.push(r);
    students[r.name].scoreSum += r.score;
    students[r.name].totalSum += r.total;
    students[r.name].date = r.date;
  });

  list.innerHTML = '';

  Object.values(students).forEach((s) => {
    const percent = Math.round((s.scoreSum / s.totalSum) * 100);

    const subjectLines = s.subjects
      .map(
        (sub) =>
          `<div class="ubt-subject-line">
             <span>${sub.subject}</span>
             <strong>${sub.score}/${sub.total} (${sub.percent}%)</strong>
           </div>`
      )
      .join('');

    list.innerHTML += `
      <div class="ubt-result-row">
        <div class="ubt-result-info">
          <strong>${s.name}</strong>
          <div class="ubt-subjects-mini">${subjectLines}</div>
          <small>Соңғы тапсырған уақыты: ${s.date}</small>
        </div>
        <div class="ubt-result-score">
          ${s.scoreSum}/${s.totalSum}
          <span>${percent}%</span>
          <button
            class="ubt-delete-btn"
            onclick="deleteUBTStudent('${s.name.replace(/'/g, "\\'")}')"
            title="Өшіру"
          >
            🗑️
          </button>
        </div>
      </div>
    `;
  });
}
