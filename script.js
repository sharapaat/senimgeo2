/* =====================================================
   ҰБТ — СҰРАҚ ЖҮКТЕУ
===================================================== */

function loadUBTQuestion() {
  const questions = ubtQuestions[ubtCurrentSubject];
  const q = questions[ubtCurrentIndex];

  document.getElementById('ubtCurrent').textContent = ubtCurrentIndex + 1;
  document.getElementById('ubtProgressBar').style.width =
    ((ubtCurrentIndex + 1) / questions.length) * 100 + '%';

  document.getElementById('ubtQuestionText').textContent = q.q;

  const answersBox = document.getElementById('ubtAnswers');
  answersBox.innerHTML = '';
  document.getElementById('ubtAnswerResult').innerHTML = '';
  document.getElementById('ubtNextButton').style.display = 'none';

  ubtAnswered = false;

  // ---- ЖАУАПТАРДЫ АРАЛАСТЫРУ ----
  // Дұрыс жауаптың индексін сақтап, варианттарды shuffle жасаймыз
  const indexed = q.a.map((text, i) => ({ text, isCorrect: i === q.c }));

  // Fisher-Yates shuffle
  for (let i = indexed.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [indexed[i], indexed[j]] = [indexed[j], indexed[i]];
  }

  // Араласқаннан кейінгі дұрыс жауаптың жаңа индексін табамыз
  const newCorrectIndex = indexed.findIndex((item) => item.isCorrect);

  // Осы сұрақ үшін уақытша дұрыс индексті сақтаймыз
  ubtCurrentCorrectIndex = newCorrectIndex;

  indexed.forEach((item, index) => {
    const btn = document.createElement('button');
    btn.className = 'answer';
    btn.textContent = `${String.fromCharCode(65 + index)}. ${item.text}`;
    btn.onclick = () => selectUBTAnswer(index, btn);
    answersBox.appendChild(btn);
  });
}

