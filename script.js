function showWorldMap() {
  const noMapTopics = ['climate', 'relief', 'population'];

  const mapContainer = document.getElementById('quizMap');
  const mapTitle = document.getElementById('mapTitle');

  // Карта керек емес тесттер
  if (noMapTopics.includes(currentTopic)) {
    // Картаның өзін жасыру
    if (mapContainer) {
      mapContainer.style.display = 'none';
    }

    // Карта тақырыбын жасыру
    if (mapTitle) {
      mapTitle.style.display = 'none';
    }

    // Карта тұрған барлық бос блоктарды табу
    if (mapContainer) {
      let parent = mapContainer.parentElement;

      if (parent) {
        parent.style.display = 'none';
      }
    }

    return;
  }

  // Басқа тесттерде карта қайта пайда болады
  if (mapContainer) {
    mapContainer.style.display = 'block';

    let parent = mapContainer.parentElement;
    if (parent) {
      parent.style.display = '';
    }
  }

  if (mapTitle) {
    mapTitle.style.display = 'block';
    mapTitle.textContent = 'Әлем картасы';
  }

  if (!quizMap) {
    initQuizMap();
    return;
  }

  quizMap.setView([20, 0], 2);

  quizMap.eachLayer((layer) => {
    if (
      layer instanceof L.Marker ||
      layer instanceof L.Circle ||
      layer instanceof L.Polygon
    ) {
      quizMap.removeLayer(layer);
    }
  });
}

